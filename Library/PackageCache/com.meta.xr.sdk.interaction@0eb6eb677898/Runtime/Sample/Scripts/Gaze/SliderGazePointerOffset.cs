using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;

namespace Oculus.Interaction.Gaze.Samples
{
    [RequireComponent(typeof(Slider))]
    public class SliderGazePointerOffset : MonoBehaviour
    {
        private Slider _slider;
        [SerializeField]
        // RectTransform that should cover all the child target
        // elements of the slider.
        private RectTransform _blockerRect;
        private bool _blockerAutogenerated = false;
        // Selectable used to relay events to this component
        private EventTrigger _blockerTriggers;
        // Raycast target for the blocker
        private Image _blockerTarget;
        // Pointer offset in screen space
        private Vector2 pointerOffset;
        protected bool _started = false;

        protected virtual void Start()
        {
            this.BeginStart(ref _started);
            _slider = GetComponent<Slider>();
            this.AssertField(_slider, nameof(_slider));

            if (_slider.handleRect != null)
            {
                if (_blockerRect == null) CreateDefaultBlocker();
                AddRayTargetToBlocker(_blockerRect);
                AddEventsToBlockingRect(_blockerRect);
            }
            else
            {
                Debug.LogWarning("Slider component is missing `HandleRect`");
                this.enabled = false;
            }
            this.EndStart(ref _started);
        }

        private void CreateDefaultBlocker()
        {
            var blocker = new GameObject("EventBlocker");
            blocker.transform.SetParent(this.transform, false);
            _blockerRect = blocker.AddComponent<RectTransform>();
            _blockerRect.anchorMin = Vector2.zero;
            _blockerRect.anchorMax = Vector2.one;
            _blockerRect.pivot = Vector2.one * 0.5f;
            _blockerRect.sizeDelta = Vector2.zero;
            _blockerAutogenerated = true;
        }

        private void AddRayTargetToBlocker(RectTransform blocker)
        {
            _blockerTarget = blocker.gameObject.AddComponent<Image>();
            _blockerTarget.raycastTarget = true;
            _blockerTarget.alphaHitTestMinimumThreshold = -1.0f;
            _blockerTarget.color = new Color(1.0f, 0.0f, 0.0f, 0.0f);
        }

        private void AddEventsToBlockingRect(RectTransform blocker)
        {
            _blockerTriggers = blocker.gameObject.AddComponent<EventTrigger>();
            EventTrigger.Entry pointerDown = new EventTrigger.Entry();
            pointerDown.eventID = EventTriggerType.PointerDown;
            pointerDown.callback.AddListener((data) => { OnPointerDown((PointerEventData)data); });
            _blockerTriggers.triggers.Add(pointerDown);

            EventTrigger.Entry pointerUp = new EventTrigger.Entry();
            pointerUp.eventID = EventTriggerType.PointerUp;
            pointerUp.callback.AddListener((data) => { OnPointerUp((PointerEventData)data); });
            _blockerTriggers.triggers.Add(pointerUp);

            EventTrigger.Entry pointerDrag = new EventTrigger.Entry();
            pointerDrag.eventID = EventTriggerType.Drag;
            pointerDrag.callback.AddListener((data) => { OnDrag((PointerEventData)data); });
            _blockerTriggers.triggers.Add(pointerDrag);

            EventTrigger.Entry pointerMove = new EventTrigger.Entry();
            pointerMove.eventID = EventTriggerType.Move;
            pointerMove.callback.AddListener((data) => { OnMove((AxisEventData)data); });
            _blockerTriggers.triggers.Add(pointerMove);
        }

        private PointerEventData OffsetPointerEvent(PointerEventData data)
        {
            data.position += pointerOffset;
            return data;
        }

        private bool IsFromGazeInteractor(int pointerId)
        {
            UniqueIdentifier.TryGetInstanceFromIdentifier<GazeInteractor>(Context.Global.GetInstance(), pointerId, out var gazeInteractor);
            return gazeInteractor != null;
        }

        private Vector3[] _corners = new Vector3[4];
        private void OnPointerDown(PointerEventData data)
        {
            pointerOffset = Vector2.zero;
            if (_slider.handleRect != null && IsFromGazeInteractor(data.pointerId))
            {
                _slider.handleRect.GetWorldCorners(_corners);
                var handleCenter = (_corners[0] + _corners[2]) / 2.0f;
                var handleScreenPosition = RectTransformUtility.WorldToScreenPoint(data.pressEventCamera, handleCenter);
                pointerOffset = handleScreenPosition - data.position;
            }
            _slider.OnPointerDown(OffsetPointerEvent(data));
        }

        private void OnPointerUp(PointerEventData data)
        {
            _slider.OnPointerUp(OffsetPointerEvent(data));
        }

        private void OnDrag(PointerEventData data)
        {
            _slider.OnDrag(OffsetPointerEvent(data));
        }

        private void OnMove(AxisEventData data)
        {
            _slider.OnMove(data);
        }

        #region Inject

        public void InjectAllSliderOffset(RectTransform blocker)
        {
            InjectBlocker(blocker);
        }
        public void InjectBlocker(RectTransform blocker)
        {
            if (_blockerAutogenerated)
            {
                Destroy(_blockerRect);
                _blockerAutogenerated = false;
            }
            else
            {
                Destroy(_blockerTriggers);
                Destroy(_blockerTarget);
            }

            _blockerRect = blocker;

            if (_started && _blockerRect != null)
            {
                AddRayTargetToBlocker(_blockerRect);
                AddEventsToBlockingRect(_blockerRect);
            }
        }

        #endregion Inject
    }
}

