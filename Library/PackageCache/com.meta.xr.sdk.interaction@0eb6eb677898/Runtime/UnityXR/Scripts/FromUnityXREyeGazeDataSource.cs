using System;
using System.Linq;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Oculus.Interaction.Input.UnityXR
{
    [Experimental]
    public class FromUnityXREyeGazeDataSource : DataSource<EyeGazeDataAsset>
    {
        [Flags]
        private enum TrackingState
        {
            /// <summary>
            /// Position and rotation are not valid.
            /// </summary>
            None,

            /// <summary>
            /// Position is valid.
            /// See <c>InputTrackingState.Position</c>.
            /// </summary>
            Position = 1 << 0,

            /// <summary>
            /// Rotation is valid.
            /// See <c>InputTrackingState.Rotation</c>.
            /// </summary>
            Rotation = 1 << 1,
        }

        private const string _eyeGazeInteractionActionMap = @"{
            ""maps"": [
                {
                    ""name"": ""Eye Gaze Interaction"",
                    ""actions"": [
                        {
                            ""name"": ""Position"",
                            ""expectedControlLayout"": ""Vector3"",
                            ""bindings"": [
                                {
                                    ""path"":""<EyeGaze>/pose/position""
                                }
                            ]
                        },
                        {
                            ""name"": ""Rotation"",
                            ""expectedControlLayout"": ""Quaternion"",
                            ""bindings"": [
                                {
                                    ""path"":""<EyeGaze>/pose/rotation""
                                }
                            ]
                        },
                        {
                            ""name"": ""TrackingState"",
                            ""expectedControlLayout"": ""Integer"",
                            ""bindings"": [
                                {
                                    ""path"":""<EyeGaze>/pose/trackingState""
                                }
                            ]
                        }
                    ]
                }
            ]}";

        [SerializeField]
        private InputActionMap _eyeGazeInteractionBindings =
            InputActionMap.FromJson(_eyeGazeInteractionActionMap).FirstOrDefault();

        [SerializeField]
        [Optional(OptionalAttribute.Flag.AutoGenerated | OptionalAttribute.Flag.DontHide)]
        private Camera _centerEyeCamera;

        [SerializeField]
        [Interface(typeof(ITrackingToWorldTransformer))]
        private UnityEngine.Object _trackingToWorldTransformer;
        private ITrackingToWorldTransformer TrackingToWorldTransformer;

        protected override EyeGazeDataAsset DataAsset => _dataAsset;

        private readonly EyeGazeDataAsset _dataAsset = new EyeGazeDataAsset();

        private InputAction _gazePosition;
        private InputAction _gazeRotation;
        private InputAction _gazeTrackingState;

        protected virtual void Awake()
        {
            if (_centerEyeCamera == null)
            {
                _centerEyeCamera = Camera.main;
            }
            if (TrackingToWorldTransformer == null)
            {
                TrackingToWorldTransformer = _trackingToWorldTransformer as ITrackingToWorldTransformer;
            }
        }

        protected override void Start()
        {
            this.BeginStart(ref _started, () => base.Start());

            this.AssertField(_centerEyeCamera, nameof(_centerEyeCamera));
            this.AssertField(TrackingToWorldTransformer, nameof(TrackingToWorldTransformer));
            _gazePosition = _eyeGazeInteractionBindings["Position"];
            _gazeRotation = _eyeGazeInteractionBindings["Rotation"];
            _gazeTrackingState = _eyeGazeInteractionBindings["TrackingState"];

            this.EndStart(ref _started);
        }

#if UNITY_EDITOR

        protected virtual void Reset()
        {
            base.InjectUpdateMode(UpdateModeFlags.UnityUpdate);
        }

#endif // UNITY_EDITOR

        protected override void OnEnable()
        {
            base.OnEnable();
            if (_started)
            {
                _eyeGazeInteractionBindings.Enable();
            }
        }

        protected override void OnDisable()
        {
            if (_started)
            {
                _eyeGazeInteractionBindings.Disable();
            }
            base.OnDisable();
            MarkInputDataRequiresUpdate();
        }

        protected override void UpdateData()
        {
            _dataAsset.FrameId = Time.frameCount;
            _dataAsset.IsTracked = false;
            _dataAsset.WorldPose = Pose.identity;
            _dataAsset.WorldPoseOrigin = PoseOrigin.None;
            _dataAsset.CameraWorldPose = _centerEyeCamera.transform.GetPose();

            if (_started)
            {
                var trackingState = (TrackingState)_gazeTrackingState.ReadValue<int>();

                if (trackingState.HasFlag(TrackingState.Position) &&
                    trackingState.HasFlag(TrackingState.Rotation))
                {
                    Pose trackingPose = new Pose(
                      _gazePosition.ReadValue<Vector3>(),
                      _gazeRotation.ReadValue<Quaternion>());
                    Pose worldPose = TrackingToWorldTransformer.ToWorldPose(trackingPose);

                    _dataAsset.IsTracked = true;
                    _dataAsset.WorldPose = worldPose;
                    _dataAsset.WorldPoseOrigin = PoseOrigin.RawTrackedPose;
                }
            }
        }

        #region Inject

        public void InjectAllFromUnityXREyeGazeDataSource(
            UpdateModeFlags updateMode,
            IDataSource updateAfter,
            Camera centerEyeCamera,
            ITrackingToWorldTransformer transformer)
        {
            base.InjectAllDataSource(updateMode, updateAfter);
            InjectCenterEyeCamera(centerEyeCamera);
            InjectTrackingToWorldTransformer(transformer);
        }

        public void InjectCenterEyeCamera(Camera centerEyeCamera)
        {
            _centerEyeCamera = centerEyeCamera;
        }

        public void InjectTrackingToWorldTransformer(ITrackingToWorldTransformer transformer)
        {
            _trackingToWorldTransformer = transformer as UnityEngine.Object;
            TrackingToWorldTransformer = transformer;
        }

        #endregion
    }
}
