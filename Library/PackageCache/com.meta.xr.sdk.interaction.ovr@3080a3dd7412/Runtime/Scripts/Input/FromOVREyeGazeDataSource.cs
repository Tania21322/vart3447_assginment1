using UnityEngine;

namespace Oculus.Interaction.Input
{
    [Experimental]
    public class FromOVREyeGazeDataSource : DataSource<EyeGazeDataAsset>
    {
        private const string LOG_PREFIX = nameof(FromOVREyeGazeDataSource);

        [Header("OVR Data Source")]
        [SerializeField, Interface(typeof(IOVRCameraRigRef))]
        [Optional(OptionalAttribute.Flag.AutoGenerated | OptionalAttribute.Flag.DontHide)]
        private UnityEngine.Object _cameraRigRef;
        private IOVRCameraRigRef CameraRigRef = null;

        [SerializeField]
        [Optional(OptionalAttribute.Flag.AutoGenerated | OptionalAttribute.Flag.DontHide)]
        private Camera _centerEyeCamera;

        [SerializeField]
        private bool _processLateUpdates = false;

        public bool ProcessLateUpdates
        {
            get => _processLateUpdates;
            set => _processLateUpdates = value;
        }

        protected override EyeGazeDataAsset DataAsset => _dataAsset;

        private readonly EyeGazeDataAsset _dataAsset = new EyeGazeDataAsset();

        private bool _eyeTrackingAvailable = false;

        protected virtual void Awake()
        {
            if (_centerEyeCamera == null)
            {
                _centerEyeCamera = Camera.main;
            }

            if (_cameraRigRef == null)
            {
                _cameraRigRef = GetComponentInParent<OVRCameraRigRef>();
            }

            if (CameraRigRef == null)
            {
                CameraRigRef = _cameraRigRef as IOVRCameraRigRef;
            }

            _eyeTrackingAvailable = OVRPlugin.eyeGazeInteractionsSupported;
        }

        protected override void Start()
        {
            this.BeginStart(ref _started, () => base.Start());
            this.AssertField(CameraRigRef, nameof(CameraRigRef));
            this.AssertField(_centerEyeCamera, nameof(_centerEyeCamera));
            this.EndStart(ref _started);
        }

        protected override void OnEnable()
        {
            base.OnEnable();

            if (_started)
            {
                CameraRigRef.WhenInputDataDirtied += HandleInputDataDirtied;

                if (!_eyeTrackingAvailable)
                {
                    Debug.Log($"[{LOG_PREFIX}] Failed to start eye tracking.");
                }
                else
                {
                    Debug.Log($"[{LOG_PREFIX}] Eye tracking started.");
                }
            }
        }

        protected override void OnDisable()
        {
            if (_started)
            {
                CameraRigRef.WhenInputDataDirtied -= HandleInputDataDirtied;
            }

            base.OnDisable();
            MarkInputDataRequiresUpdate();
        }

        private void HandleInputDataDirtied(bool isLateUpdate)
        {
            if (isLateUpdate && !_processLateUpdates)
            {
                return;
            }
            MarkInputDataRequiresUpdate();
        }

        protected override void UpdateData()
        {
            _dataAsset.FrameId = Time.frameCount;
            _dataAsset.IsTracked = false;
            _dataAsset.WorldPose = Pose.identity;
            _dataAsset.WorldPoseOrigin = PoseOrigin.None;
            _dataAsset.CameraWorldPose = _centerEyeCamera.transform.GetPose();

            UpdateEyeTrackingData();
        }

        private static Pose ToWorldSpacePose(OVRPlugin.Posef pose, Camera centerEyeCamera)
        {
            OVRPose ovrPose = pose.ToOVRPose().ToWorldSpacePose(centerEyeCamera);
            return new Pose(ovrPose.position, ovrPose.orientation);
        }

        private void UpdateEyeTrackingData()
        {
            if (!_eyeTrackingAvailable || !isActiveAndEnabled)
            {
                return;
            }

            OVRPlugin.EyeGazeInteractionState state = default;
            if (!OVRPlugin.GetEyeGazeInteractionState(OVRPlugin.Step.Render, -1, ref state))
            {
                return;
            }

            if (state.IsValid)
            {
                _dataAsset.WorldPose = ToWorldSpacePose(state.Pose, _centerEyeCamera);
                _dataAsset.IsTracked = true;
            }
            else
            {
                _dataAsset.WorldPose = Pose.identity;
                _dataAsset.IsTracked = false;
            }

        }

        #region Inject

        public void InjectAllFromOVREyeGazeDataSource(UpdateModeFlags updateMode, IDataSource updateAfter,
            Camera centerEyeCamera)
        {
            base.InjectAllDataSource(updateMode, updateAfter);
            InjectCenterEyeCamera(centerEyeCamera);
        }

        private void InjectCenterEyeCamera(Camera centerEyeCamera)
        {
            _centerEyeCamera = centerEyeCamera;
        }

        #endregion
    }
}
